CREATE OR REPLACE FUNCTION fn_loan_fine(p_loan_id INT,p_as_of DATE)
RETURNS NUMERIC(10,2) LANGUAGE plpgsql AS $$
DECLARE v_due DATE;v_returned DATE;v_end DATE;
BEGIN
 SELECT due_on,returned_on INTO v_due,v_returned FROM loans WHERE loan_id=p_loan_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID %',p_loan_id; END IF;
 IF p_as_of IS NULL THEN RAISE EXCEPTION 'As-of date cannot be NULL'; END IF;
 v_end:=LEAST(p_as_of,COALESCE(v_returned,p_as_of));
 RETURN GREATEST(v_end-v_due,0)*2.00;
END; $$;

CREATE OR REPLACE FUNCTION trg_loan_audit_fn()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.returned_on IS DISTINCT FROM NEW.returned_on THEN
  INSERT INTO loan_audit(loan_id,old_returned_on,new_returned_on)
  VALUES(NEW.loan_id,OLD.returned_on,NEW.returned_on);
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER trg_loan_audit AFTER UPDATE OF returned_on ON loans
FOR EACH ROW EXECUTE FUNCTION trg_loan_audit_fn();

CREATE OR REPLACE PROCEDURE pr_return_loan(p_loan_id INT,p_returned_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_borrowed DATE;v_due DATE;v_old_return DATE;
BEGIN
 SELECT borrowed_on,due_on,returned_on INTO v_borrowed,v_due,v_old_return
 FROM loans WHERE loan_id=p_loan_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan'; END IF;
 IF v_old_return IS NOT NULL THEN RAISE EXCEPTION 'Loan already returned'; END IF;
 IF p_returned_on IS NULL OR p_returned_on<v_borrowed THEN RAISE EXCEPTION 'Invalid return date'; END IF;
 UPDATE loans SET returned_on=p_returned_on,
 fine_amount=GREATEST(p_returned_on-v_due,0)*2.00 WHERE loan_id=p_loan_id;
END; $$;

